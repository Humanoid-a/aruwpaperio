"""A fingerprint of everything that decides Q's inputs.

Logged inputs are only valid for the code that produced them: a change to the belief, the memory, the adapter, the
snapshot or an input builder changes what the agent would have seen. inputs_version() hashes the source of exactly
those modules (line endings normalised) plus the configuration values the inputs read, so a training set can tell
which records are stale. A stale record is regenerated by replaying its move tape (candidate/offline/replay.py).
Moving or renaming one of these files changes the fingerprint too, which only costs a replay.
"""

import hashlib
from dataclasses import fields
from functools import lru_cache
from pathlib import Path

from candidate.agent.behavior.config import BEHAVIOR, BehaviorConfig
from candidate.agent.q.config import Q, QConfig

_AGENT = Path(__file__).resolve().parents[1]

_SOURCES = (
    "config.py", "adapter.py", "runtime.py", "prediction.py",
    "belief/*.py", "data/*.py", "geometry/*.py", "rules/*.py",
    "behavior/states.py", "behavior/votes.py", "behavior/snapshot.py", "behavior/worldmap.py", "behavior/maps.py", "behavior/paths.py",
    "q/features.py", "q/grid.py", "q/probmap.py", "q/inputs.py",
)

# the configuration values the snapshot (BehaviorConfig) and the input builders (QConfig) read; the rest only steer play
_BEHAVIOR_FIELDS = (
    "possible_min_probability", "known_trail_probability", "distance_cap", "margin_offset", "since_sighting_cap",
    "position_threshold", "trail_threshold", "land_threshold",
)
_Q_FIELDS = (
    "grid_crop", "probmap_block", "scale_distance", "margin_clip", "scale_trail", "scale_count", "scale_gain",
    "scale_turns", "scale_since_sighting", "belief_spread_cells",
)


def _source_files() -> list[Path]:
    out: list[Path] = []
    for pattern in _SOURCES:
        out.extend(sorted(_AGENT.glob(pattern)))
    return out


@lru_cache(maxsize=8)
def inputs_version(cfg: QConfig = Q, behavior: BehaviorConfig = BEHAVIOR) -> str:
    digest = hashlib.sha1()
    for path in _source_files():
        digest.update(path.relative_to(_AGENT).as_posix().encode())
        digest.update(path.read_bytes().replace(b"\r\n", b"\n"))
    for config, names in ((behavior, _BEHAVIOR_FIELDS), (cfg, _Q_FIELDS)):
        known = {f.name for f in fields(config)}
        for name in names:
            assert name in known, name
            digest.update(f"{name}={getattr(config, name)!r}".encode())
    return digest.hexdigest()[:16]
